def draw(px, text, x, y, scale=2, color=(0.1, 0.1, 0.1)):
    """Draw `text` into float RGBA array px (rows bottom-up, as Blender stores them) with its
    top-left corner at pixel (x, y) counted from the top. Unknown characters are skipped."""
    h = px.shape[0]
    for i, ch in enumerate(text.upper()):
        g = _G.get(ch)
        if g is None:
            continue
        bits = np.array([int(b) for b in g], dtype=bool).reshape(7, 5)
        big = np.kron(bits, np.ones((scale, scale), dtype=bool))
        x0 = x + i * 6 * scale
        y_top = y
        for r in range(big.shape[0]):
            row = h - 1 - (y_top + r)
            if not 0 <= row < h:
                continue
            cols = np.nonzero(big[r])[0] + x0
            cols = cols[(cols >= 0) & (cols < px.shape[1])]
            px[row, cols, :3] = color
    return px


def width(text, scale=2):
    return len(text) * 6 * scale
